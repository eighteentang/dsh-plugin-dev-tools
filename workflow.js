/**
 * 开发工具箱 —— 「开工前定需求」工作流
 *
 * ── 为什么单独一个模块 ────────────────────────────────────────
 *
 * `dev-rule.js` 的自检清单管的是**怎么动手**（查文档 / 查槽位 / 抄实现）。
 * 但还有一种失败模式它管不到：
 *
 *   **用户说"我想做一个 XX 功能"，我就开始规划了 —— 而需求根本没定。**
 *
 * 后果是规划跑偏、做完才发现不是用户要的、或者没搞清放哪个工作空间。
 * 这个模块补的就是这一关：**需求确认 → 规划 → 开工**，一次授权只走一步。
 *
 * ── 为什么进"注入"而不是只写经验库 ────────────────────────────
 *
 * 经验库是**按需查阅的资料**：我得先意识到"该查"才会去查。
 * 而这条是**每次都要走的关卡** —— 放进注入内容才是强制的（见经验库 E19）。
 * 经验库里放"为什么这样设计"（给人看），这里放"每次怎么做"（给 AI 执行）。
 *
 * ── 写法要求：这是清单，不是文档 ──────────────────────────────
 *
 * 第一版写了 1054 字符，把"为什么"也写进去了 —— 结果注入总量超预算。
 * 所以：**这里只留可执行的动作**，理由写进代码注释和经验库。
 */

/**
 * 生成"开工前定需求"那一段注入文本。
 * @returns {string}
 */
export function buildWorkflowText() {
  return [
    '',
    '## 开工前定需求（用户说"我想做一个 XX"时，先走这一关）',
    '',
    '触发：新功能 / 新插件 / 新产品的意图。不触发：小修小改、已在进行的下一步。',
    '',
    '**① 先对齐四要素，再谈规划**',
    '',
    '   名字 / 用途 / 使用场景 / 工作空间（目录）',
    '',
    '⚠ 不要走四次顺序问答（中途取消即丢、不能回改）。做法：',
    '   · **能从上下文推断的先填好**，标注"（推断）"',
    '   · **只问真正缺的**，能合并就一次问完',
    '   · 整理成清单**在对话里发出来**，请用户确认',
    '   · **只记用户说的** —— 想加功能先说"我建议加 XX，要吗"，等他点头',
    '',
    '**② 一次确认只授权一步**',
    '',
    '   用户确认四要素  → 只做**规划**（步骤 / 动哪些文件 / 怎么验证）',
    '   规划再确认      → 才动手',
    '   ↑ 打「确认」时确认的是四要素，**不是你的规划**，别合并成一步',
    '',
    '**③ 工作空间不要越权**',
    '',
    '   · 用户没提 → **不要自动新建**，先问"建在哪"或给建议路径让他选',
    '   · 用户说"你看着办" → 给一个路径 + 一句话理由，等同意再建',
    '   · 要新建时顺手放一份 `AGENTS.md`（目录结构 / 验证命令 / 已知的坑）',
    '     —— 没有它，下一轮进这个目录就什么都不知道',
    '',
    '**④ 写进"记忆"，否则下个会话就忘了**',
    '',
    '   · 项目专属约定 → 那个工作空间的 `AGENTS.md`',
    '   · 通用方法论   → 经验库',
  ].join('\n');
}
